"""Generate the asynchronous browser engine from the CLI's parser/runtime.

The two execution adapters remain separate; shared language fixes are generated
into the browser artifact so they cannot silently diverge. No user code is run.
"""
import ast
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[1]
ASYNC_METHODS = {'exec_block', 'exec', '_exec', 'eval', 'call', 'eval_builtin'}


class AsyncInterpreter(ast.NodeTransformer):
    def visit_FunctionDef(self, node):
        node = self.generic_visit(node)
        if node.name not in ASYNC_METHODS:
            return node
        if node.name == 'eval_builtin':
            node.body = ast.parse('''
result = BUILTINS[name](args)
if hasattr(result, '__await__') or hasattr(result, 'then'):
    result = await result
return result
''').body
        return ast.AsyncFunctionDef(
            name=node.name, args=node.args, body=node.body,
            decorator_list=node.decorator_list, returns=node.returns,
            type_comment=node.type_comment,
        )

    def visit_Call(self, node):
        node = self.generic_visit(node)
        if (isinstance(node.func, ast.Attribute)
                and isinstance(node.func.value, ast.Name)
                and node.func.value.id == 'self'
                and node.func.attr in ASYNC_METHODS):
            return ast.Await(value=node)
        return node


ADAPTER = '''
import contextlib
import io
try:
    import js
except ImportError:
    js = None

def browser_input(args):
    prompt = str(args[0]) if args else ''
    if js is None:
        return input(prompt)
    print(prompt, end='')
    return js.getMozhiInput(prompt)

BUILTINS['kelu'] = browser_input
BUILTINS['ketukko'] = browser_input

def local_files_only(args):
    raise OSError('File I/O is local-only; the playground does not expose host files.')

for name in ('padi', 'ezhuthu', 'serthu_ezhuthu'):
    BUILTINS[name] = local_files_only

class BrowserOutput(io.StringIO):
    def write(self, text):
        if js is not None:
            js.appendMozhiOutput(text)
            return len(text)
        return super().write(text)

async def execute_mozhi(source):
    output = BrowserOutput()
    error = None
    with contextlib.redirect_stdout(output):
        try:
            statements = Parser(tokenize(source)).parse()
            await Interpreter().exec_block(statements, Environment())
        except ExitSignal:
            pass
        except (MozhiError, SyntaxError) as failure:
            error = str(failure)
    return {'output': output.getvalue(), 'error': error}
'''


def generate():
    tree = ast.parse((ROOT / 'src' / 'mozhi' / 'core.py').read_text(encoding='utf-8'))
    nodes = []
    for node in tree.body:
        if (isinstance(node, ast.Assign)
                and any(isinstance(t, ast.Name) and t.id == 'EXAMPLE' for t in node.targets)):
            break
        if isinstance(node, ast.ClassDef) and node.name == 'Interpreter':
            node = AsyncInterpreter().visit(node)
        nodes.append(node)
    module = ast.fix_missing_locations(ast.Module(body=nodes, type_ignores=[]))
    return '# Generated by tools/sync_playground.py; edit src/mozhi/core.py instead.\n' + ast.unparse(module) + '\n' + ADAPTER.lstrip()


if __name__ == '__main__':
    (ROOT / 'playground' / 'runtime.py').write_bytes(generate().encode('utf-8'))
